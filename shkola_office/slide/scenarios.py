def build(name: str, ratio: str = "16:9") -> Presentation:
    theme, steps = SCENARIOS[name]
    pres = Presentation(ratio=ratio, theme=theme, font=THEMES[theme].font, title=name)
    for layout, data, notes in steps:
        if layout == "quiz":
            s = make_quiz_slide(pres, data)
        else:
            s = make_slide(layout, pres)
            texted = [e for e in s.elements if e.role != "decor" and e.text]
            for e, t in zip(texted, data):
                if t is not None:
                    e.text = t
        s.notes = notes
        pres.slides.append(s)
    return pres
